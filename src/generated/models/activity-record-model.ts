import type { ProvisioningRequest } from './provisioning-request-model';
import type { RequestedUser } from './requested-user-model';

export const ActivityRecordActionTypeKeyToLabel = {
  'IntakeCreated': 'Intake Created',
  'UserAdded': 'User Added',
  'SentToProvisioning': 'Sent to Provisioning',
  'ConfirmationUpdated': 'Confirmation Updated',
  'NotificationSent': 'Notification Sent',
  'ExceptionLogged': 'Exception Logged',
  'RequestOnHold': 'Request On Hold',
  'RequestResumed': 'Request Resumed'
} as const;
export type ActivityRecordActionTypeKey = keyof typeof ActivityRecordActionTypeKeyToLabel;

export interface ActivityRecord {
  /**
   * @displayName Activity Record
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Activity Record Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  activityRecordName: string;
  /**
   * @displayName Action Type
   * @validationRule Required for create/update operations
   */
  actionTypeKey: ActivityRecordActionTypeKey;
  /**
   * @displayName Actor Email
   * @validationRule Required for create/update operations
   */
  actorEmail: string;
  /**
   * @displayName Actor Name
   * @validationRule Required for create/update operations
   */
  actorName: string;
  /**
   * @displayName Description
   * @validationRule Required for create/update operations
   */
  description: string;
  /**
   * @displayName Provisioning Request
   * @validationRule Required for create/update operations
   */
  provisioningRequest: Pick<ProvisioningRequest, 'id' | 'provisioningRequestName'>;
  /**
   * @displayName Requested User
   */
  requestedUser?: Pick<RequestedUser, 'id' | 'fullName'>;
  /**
   * @displayName Timestamp
   * @validationRule Required for create/update operations
   */
  timestamp: string;
}

export const _ActivityRecord = 'ActivityRecord' as const;