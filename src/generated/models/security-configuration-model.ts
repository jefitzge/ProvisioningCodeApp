import type { Application } from './application-model';
import type { Environment } from './environment-model';

export const SecurityConfigurationArchitectureKeyToLabel = {
  'DirectRole': 'Direct Role',
  'TeamBased': 'Team Based',
  'Combined': 'Combined'
} as const;
export type SecurityConfigurationArchitectureKey = keyof typeof SecurityConfigurationArchitectureKeyToLabel;

export const SecurityConfigurationConfigurationTypeKeyToLabel = {
  'DirectRole': 'Direct Role',
  'OwnerTeam': 'Owner Team',
  'AccessTeam': 'Access Team',
  'SecurityGroup': 'Security Group'
} as const;
export type SecurityConfigurationConfigurationTypeKey = keyof typeof SecurityConfigurationConfigurationTypeKeyToLabel;

export interface SecurityConfiguration {
  /**
   * @displayName Security Configuration
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Security Configuration Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  securityConfigurationName: string;
  /**
   * @displayName Active State
   * @validationRule Required for create/update operations
   */
  activeState: boolean;
  /**
   * @displayName Application
   */
  application?: Pick<Application, 'id' | 'applicationName'>;
  /**
   * @displayName Architecture
   * @validationRule Required for create/update operations
   */
  architectureKey: SecurityConfigurationArchitectureKey;
  /**
   * @displayName Configuration Type
   * @validationRule Required for create/update operations
   */
  configurationTypeKey: SecurityConfigurationConfigurationTypeKey;
  /**
   * @displayName Environment
   * @validationRule Required for create/update operations
   */
  environment: Pick<Environment, 'id' | 'environmentName'>;
  /**
   * @displayName Instructions
   * @validationRule Required for create/update operations
   */
  instructions: string;
}

export const _SecurityConfiguration = 'SecurityConfiguration' as const;